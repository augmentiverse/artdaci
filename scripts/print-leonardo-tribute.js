const lang = ["en", "fr", "ar"].includes(params.get("lang")) ? params.get("lang") : "en";
const copy = COPY[lang];
const root = document.getElementById("tribute-print");

document.documentElement.lang = lang;
document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
document.title = copy.documentTitle;
document.getElementById("tribute-back").textContent = copy.back;
document.getElementById("tribute-back").href = lang === "ar" ? "index-ar.html" : lang === "fr" ? "index-fr.html" : "index.html";

copy.pages.forEach((page, index) => {
  const article = document.createElement("article");
  article.className = `tribute-print-page tribute-print-page-${index + 1}`;
  article.innerHTML = `
    <img class="artdaci-logo tribute-page-logo" src="assets/varia/artdaci-logo.png" alt="ARTDACI" />
    <div class="tribute-print-copy">
      <p class="eyebrow">${page.eyebrow}</p>
      <h1>${page.title}</h1>
      <p class="tribute-print-lead">${page.lead}</p>
      ${page.paragraphs.map((paragraph) => `<p>${paragraph}</p>`).join("")}
      ${page.closing ? `<div class="tribute-print-closing">${page.closing.map((line) => `<strong>${line}</strong>`).join("")}</div>` : ""}
    </div>
    ${index < 2 ? `
      <figure>
        <img src="assets/artists/leonardo-da-vinci/artworks/mona-lisa/images/davinci-monalisa.png" alt="" />
        <figcaption>ARTDACI · MASTERPIECES ALIVE</figcaption>
      </figure>` : ""}
    <footer>ARTDACI · ${String(index + 1).padStart(2, "0")}</footer>
  `;
  root.appendChild(article);
});
